#!/usr/bin/env python3
"""Writes docs/known-model-sources.md from the known-model CSVs and assets/model_sources.csv,
so every make/year/range in "Fill in from a known model" can be traced to the document it came from.
Run from the repo root after changing the CSVs: python3 scripts/known_models_sources.py"""
import collections
A = 'app/src/main/assets/'

def rows(f):
    return [l.rstrip('\n').split(',') for l in open(A + f, encoding='utf-8') if l.strip() and not l.startswith('#')]

links = [(r[0], r[1], r[2] if len(r) > 2 else '') for r in rows('model_sources.csv')]
def link(src):
    best = max((l for l in links if src.startswith(l[0])), key=lambda l: len(l[0]), default=None)
    return best

groups = collections.OrderedDict()
for r in rows('caravan_models.csv'):
    groups.setdefault(('Caravan', r[0], r[1], r[2], ','.join(r[12:])), []).append(r[3])
for r in rows('motorhome_models.csv'):
    groups.setdefault((r[2], r[0], r[1], r[3], ','.join(r[12:])), []).append(r[4])

out = ['# Known model sources', '',
       'Where the figures in **Fill in from a known model** came from, so they can be checked.',
       'Generated by `scripts/known_models_sources.py` from `app/src/main/assets/*_models.csv` and `model_sources.csv`.',
       'All figures are the makers\' approximate published ones; blank fields in the app mean the document did not publish them.', '']
for kind in ['Caravan', 'Motorhome', 'Campervan']:
    items = sorted([k for k in groups if k[0] == kind], key=lambda k: (k[1], k[2], k[3]))
    if not items: continue
    out += [f'## {kind}s', '', '| Make | Year | Range | Models | Source | Read on |', '|---|---|---|---|---|---|']
    for k in items:
        l = link(k[4])
        src = f'[{k[4]}]({l[1]})' if l else k[4] + ' (no link)'
        out.append(f'| {k[1]} | {k[2]} | {k[3]} | {", ".join(groups[k])} | {src} | {l[2] if l else ""} |')
    out.append('')
open('docs/known-model-sources.md', 'w', encoding='utf-8').write('\n'.join(out))
print(len(groups), 'groups')
